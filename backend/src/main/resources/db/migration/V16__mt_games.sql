-- MT-only data. Do not modify rehearsal membership, songs or reservations.
CREATE TABLE mt_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id BIGINT NOT NULL REFERENCES clubs(id),
  title VARCHAR(120) NOT NULL,
  buzzer_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  typing_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  buzzer_open BOOLEAN NOT NULL DEFAULT FALSE,
  buzzer_winner_team_id BIGINT,
  typing_open BOOLEAN NOT NULL DEFAULT FALSE,
  current_round_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_mt_active_event ON mt_events(club_id) WHERE ended_at IS NULL;

CREATE TABLE mt_teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES mt_events(id),
  name VARCHAR(80) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX uq_mt_team_name_active ON mt_teams(event_id, LOWER(name)) WHERE active;

CREATE TABLE mt_team_members (
  event_id BIGINT NOT NULL REFERENCES mt_events(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  team_id BIGINT NOT NULL REFERENCES mt_teams(id),
  PRIMARY KEY(event_id,user_id)
);
CREATE INDEX ix_mt_team_members_team ON mt_team_members(team_id);

CREATE TABLE mt_buzzer_exclusions (
  event_id BIGINT NOT NULL REFERENCES mt_events(id),
  team_id BIGINT NOT NULL REFERENCES mt_teams(id),
  PRIMARY KEY(event_id, team_id)
);

CREATE TABLE mt_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES mt_events(id),
  sort_order INTEGER NOT NULL,
  text VARCHAR(500) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_mt_question_order ON mt_questions(event_id,sort_order) WHERE active;

CREATE TABLE mt_typing_rounds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES mt_events(id),
  question_id BIGINT REFERENCES mt_questions(id),
  answer_snapshot VARCHAR(500) NOT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_mt_typing_running ON mt_typing_rounds(event_id) WHERE ended_at IS NULL;

CREATE TABLE mt_typing_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  round_id BIGINT NOT NULL REFERENCES mt_typing_rounds(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  team_id BIGINT NOT NULL REFERENCES mt_teams(id),
  user_name VARCHAR(50) NOT NULL,
  team_name VARCHAR(80) NOT NULL,
  content VARCHAR(500) NOT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_mt_submissions_round_id ON mt_typing_submissions(round_id,id);
CREATE INDEX ix_mt_submissions_user ON mt_typing_submissions(round_id,user_id,id DESC);

ALTER TABLE mt_events ADD CONSTRAINT fk_mt_winner_team FOREIGN KEY(buzzer_winner_team_id) REFERENCES mt_teams(id);
ALTER TABLE mt_events ADD CONSTRAINT fk_mt_current_round FOREIGN KEY(current_round_id) REFERENCES mt_typing_rounds(id);
